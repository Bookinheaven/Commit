"""
Saves a local JSON log of every commit message generated by this tool.
Stored next to the package as commit_history.json.
"""
import json
import os
from datetime import datetime

_HISTORY_FILE = os.path.normpath(
    os.path.join(os.path.dirname(__file__), "..", "commit_history.json")
)


def save(repo: str, title: str, description: str) -> None:
    """Append a commit entry to the history file."""
    history = _load()
    history.append({
        "timestamp": datetime.now().isoformat(timespec="seconds"),
        "repo": repo,
        "title": title,
        "description": description,
    })
    with open(_HISTORY_FILE, "w", encoding="utf-8") as f:
        json.dump(history, f, indent=2, ensure_ascii=False)


def _load() -> list:
    if not os.path.exists(_HISTORY_FILE):
        return []
    try:
        with open(_HISTORY_FILE, "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return []
